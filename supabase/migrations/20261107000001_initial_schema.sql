-- ==============================================================================
-- 2. CORE TABLES
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- Table: profiles
-- Extends auth.users with app-specific profile info.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    display_name TEXT NOT NULL CHECK (char_length(trim(display_name)) >= 1 AND char_length(display_name) <= 60),
    avatar_path TEXT,
    role user_role NOT NULL DEFAULT 'guardian',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.profiles IS 'User profiles extending Supabase auth.users.';
COMMENT ON COLUMN public.profiles.role IS 'Role of user: guardian (adult) or child.';

-- ------------------------------------------------------------------------------
-- Table: families
-- Represents an isolated private family workspace.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.families (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL CHECK (char_length(trim(name)) >= 2 AND char_length(name) <= 80),
    created_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.families IS 'Private family groups created and managed by guardians.';

-- ------------------------------------------------------------------------------
-- Table: family_members
-- Maps users to families with specific role and status.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.family_members (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    family_id UUID NOT NULL REFERENCES public.families(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    member_role user_role NOT NULL,
    status member_status NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_family_member UNIQUE (family_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_family_members_user ON public.family_members(user_id);
CREATE INDEX IF NOT EXISTS idx_family_members_family ON public.family_members(family_id);

COMMENT ON TABLE public.family_members IS 'Membership and status of users in families.';

-- ------------------------------------------------------------------------------
-- Table: family_invites
-- Stores single-use invitation hashes generated by guardians.
-- Token hashes are stored (SHA-256), never plain tokens.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.family_invites (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    family_id UUID NOT NULL REFERENCES public.families(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_family_invites_hash ON public.family_invites(token_hash);
CREATE INDEX IF NOT EXISTS idx_family_invites_family ON public.family_invites(family_id);

COMMENT ON TABLE public.family_invites IS 'One-time secure tokens for linking child accounts.';
COMMENT ON COLUMN public.family_invites.token_hash IS 'SHA-256 hash of the one-time invite token.';

-- ------------------------------------------------------------------------------
-- Table: conversations
-- Scoped conversations within a family.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.conversations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    family_id UUID NOT NULL REFERENCES public.families(id) ON DELETE CASCADE,
    conversation_type conversation_type NOT NULL DEFAULT 'direct',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_conversations_family ON public.conversations(family_id);

COMMENT ON TABLE public.conversations IS 'Conversations scoped to a specific family.';

-- ------------------------------------------------------------------------------
-- Table: conversation_members
-- Maps users to conversations (composite PK).
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.conversation_members (
    conversation_id UUID NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (conversation_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_conv_members_user ON public.conversation_members(user_id);

COMMENT ON TABLE public.conversation_members IS 'Participants of conversations.';

-- ------------------------------------------------------------------------------
-- Table: messages
-- Message history with strict length checks and cursor pagination support.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    conversation_id UUID NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    body TEXT NOT NULL CHECK (char_length(body) >= 1 AND char_length(body) <= 4000),
    message_type message_type NOT NULL DEFAULT 'text',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    edited_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ
);

-- Composite index for fast cursor-based pagination
CREATE INDEX IF NOT EXISTS idx_messages_conv_created ON public.messages(conversation_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_messages_sender ON public.messages(sender_id);

COMMENT ON TABLE public.messages IS 'Direct messages exchanged within authorized conversations.';

-- ------------------------------------------------------------------------------
-- Table: calls
-- Call sessions tracking state and timestamps.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.calls (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    family_id UUID NOT NULL REFERENCES public.families(id) ON DELETE CASCADE,
    conversation_id UUID NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    initiated_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    call_type call_type NOT NULL,
    status call_status NOT NULL DEFAULT 'ringing',
    started_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    answered_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_calls_conversation ON public.calls(conversation_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_calls_family ON public.calls(family_id);
CREATE INDEX IF NOT EXISTS idx_calls_initiated_by ON public.calls(initiated_by);

COMMENT ON TABLE public.calls IS 'Audio and video call session tracking.';

-- ------------------------------------------------------------------------------
-- Table: call_signals
-- WebRTC signaling fallback / audit table (payload size strictly capped).
-- Media data is NEVER stored here.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.call_signals (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    call_id UUID NOT NULL REFERENCES public.calls(id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    receiver_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    signal_type signal_type NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT chk_payload_size CHECK (octet_length(payload::text) <= 32768)
);

CREATE INDEX IF NOT EXISTS idx_signals_call ON public.call_signals(call_id);
CREATE INDEX IF NOT EXISTS idx_signals_receiver ON public.call_signals(receiver_id);

COMMENT ON TABLE public.call_signals IS 'Transient signaling store for WebRTC offers, answers, and candidates.';

-- ------------------------------------------------------------------------------
-- Table: push_subscriptions
-- Web Push subscriptions for notification delivery.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.push_subscriptions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    endpoint TEXT NOT NULL,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    device_label TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_user_endpoint UNIQUE (user_id, endpoint)
);

CREATE INDEX IF NOT EXISTS idx_push_user ON public.push_subscriptions(user_id);

COMMENT ON TABLE public.push_subscriptions IS 'Web Push credentials per device for background notifications.';

-- ------------------------------------------------------------------------------
-- Table: user_devices
-- Track active devices/sessions for revocation by guardians.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.user_devices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    device_label TEXT NOT NULL,
    user_agent TEXT,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_user_devices_user ON public.user_devices(user_id);

COMMENT ON TABLE public.user_devices IS 'Audit and device session tracking for revocation management.';

